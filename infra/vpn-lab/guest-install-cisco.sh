#!/bin/bash
# This script can mutate only a verified macOS virtual guest, never the host.
set -euo pipefail
task_lab_model=$(/usr/sbin/sysctl -n hw.model)
case "$task_lab_model" in
  VirtualMac*) ;;
  *) echo 'Refused: this is not a macOS virtual guest.' >&2; exit 64 ;;
esac
if [[ $(id -u) != 0 ]]; then
  echo 'Run inside the isolated guest as root.' >&2
  exit 65
fi
task_lab_share=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
test -f "$task_lab_share/guest-owner-mac"
task_lab_expected_mac=$(/bin/cat "$task_lab_share/guest-owner-mac")
if [[ ! "$task_lab_expected_mac" =~ ^([0-9a-f]{2}:){5}[0-9a-f]{2}$ ]]; then
  echo 'Refused: invalid owned guest identity.' >&2
  exit 66
fi
task_lab_actual_mac=$(/sbin/ifconfig en0 | /usr/bin/awk '/ether / {print $2}')
if [[ "$task_lab_actual_mac" != "$task_lab_expected_mac" ]]; then
  echo 'Refused: this is a different virtual guest.' >&2
  exit 67
fi
task_lab_code="$task_lab_share/cisco-code"
test -d "$task_lab_code/Applications/Cisco/Cisco Secure Client.app"
test -f "$task_lab_share/lab-ca.pem"

/usr/bin/ditto "$task_lab_code/Applications/Cisco" /Applications/Cisco
mkdir -p /opt/cisco
/usr/bin/ditto "$task_lab_code/opt/cisco/secureclient" /opt/cisco/secureclient
/usr/sbin/chown -R root:wheel /Applications/Cisco /opt/cisco/secureclient
for task_lab_app in \
  '/Applications/Cisco/Cisco Secure Client.app' \
  '/Applications/Cisco/Cisco Secure Client - Socket Filter.app' \
  '/opt/cisco/secureclient/bin/Cisco Secure Client - AnyConnect VPN Service.app'; do
  /usr/bin/codesign --verify --strict --deep "$task_lab_app"
done

# These four links are generated by the vendor postinstall and therefore
# absent from pkgutil's file receipt. Their sources remain signed resources.
/bin/bash "$task_lab_share/guest-register-cisco-plugins.sh"

mkdir -p /opt/cisco/secureclient/vpn/profile/mgmttun /opt/cisco/secureclient/vpn/script
chmod 755 /opt/cisco/secureclient/vpn/profile /opt/cisco/secureclient/vpn/profile/mgmttun /opt/cisco/secureclient/vpn/script
if [[ ! -e /opt/cisco/secureclient/ACManifestVPN.xml ]]; then
  /bin/ln -s 'bin/Cisco Secure Client - AnyConnect VPN Service.app/Contents/Resources/ACManifestVPN.xml' /opt/cisco/secureclient/ACManifestVPN.xml
fi
cat > /opt/cisco/secureclient/vpn/profile/NoSleepLab.xml <<'XML'
<?xml version="1.0" encoding="UTF-8"?>
<AnyConnectProfile xmlns="http://schemas.xmlsoap.org/encoding/" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://schemas.xmlsoap.org/encoding/ AnyConnectProfile.xsd">
  <ClientInitialization>
    <UseStartBeforeLogon UserControllable="false">false</UseStartBeforeLogon>
    <AutomaticCertSelection UserControllable="true">false</AutomaticCertSelection>
    <ShowPreConnectMessage>false</ShowPreConnectMessage>
    <AutoConnectOnStart UserControllable="true">false</AutoConnectOnStart>
    <AutoReconnect UserControllable="true">true<AutoReconnectBehavior UserControllable="true">ReconnectAfterResume</AutoReconnectBehavior></AutoReconnect>
  </ClientInitialization>
  <ServerList><HostEntry><HostName>NoSleep Lab</HostName><HostAddress>vpn-lab.invalid:4443</HostAddress><UserGroup>lab</UserGroup></HostEntry></ServerList>
</AnyConnectProfile>
XML
/usr/sbin/chown root:wheel /opt/cisco/secureclient/vpn/profile/NoSleepLab.xml
/usr/bin/security add-trusted-cert -d -r trustRoot -k /Library/Keychains/System.keychain "$task_lab_share/lab-ca.pem"
if ! /usr/bin/grep -qE '^127\.0\.0\.1[[:space:]]+vpn-lab\.invalid([[:space:]]|$)' /etc/hosts; then
  echo '127.0.0.1 vpn-lab.invalid' >> /etc/hosts
fi

# Register a guest-only service using the original signed executable. The
# host's SMAppService registration and launchd configuration are never used.
cat > /Library/LaunchDaemons/com.cisco.secureclient.vpn.service.agent.plist <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
 <key>Label</key><string>com.cisco.secureclient.vpn.service.agent</string>
 <key>ProgramArguments</key><array><string>/opt/cisco/secureclient/bin/vpnagentd</string><string>-execv_instance</string></array>
 <key>KeepAlive</key><true/>
 <key>AbandonProcessGroup</key><true/>
 <key>ExitTimeOut</key><integer>45</integer>
</dict></plist>
PLIST
/usr/sbin/chown root:wheel /Library/LaunchDaemons/com.cisco.secureclient.vpn.service.agent.plist
chmod 644 /Library/LaunchDaemons/com.cisco.secureclient.vpn.service.agent.plist
/bin/launchctl bootstrap system /Library/LaunchDaemons/com.cisco.secureclient.vpn.service.agent.plist
echo 'Guest-only signed Cisco code, test profile and test CA installed.'
